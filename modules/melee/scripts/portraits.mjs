// Writes src/battle/portraitIcons.ts: the unit icons the game uses, taken
// from the game-icons.net set (CC BY 3.0), so the app ships only these and
// not the whole set. Run with `pnpm portraits` after changing the list.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(
  readFileSync(require.resolve("@iconify-json/game-icons/icons.json"), "utf8"),
);

/** Unit def id → [icon name, author]. The set does not record authors. */
const PORTRAITS = {
  fighter: ["broadsword", "Lorc"],
  archer: ["bow-arrow", "Delapouite"],
  mage: ["pointy-hat", "Lorc"],
  healer: ["healing", "Delapouite"],
  lancer: ["spear-hook", "Lorc"],
  chronomancer: ["hourglass", "Lorc"],
  warlock: ["evil-book", "Lorc"],
  rogue: ["hood", "Lorc"],
  paladin: ["templar-shield", "Delapouite"],
  geomancer: ["crystal-cluster", "Lorc"],
  slime: ["slime", "Delapouite"],
  wolf: ["wolf-head", "Lorc"],
  viper: ["snake", "Lorc"],
  imp: ["imp", "Lorc"],
  boulder: ["stone-block", "Lorc"],
};

const entries = Object.entries(PORTRAITS).map(([id, [icon, author]]) => {
  const body = set.icons[icon]?.body;
  const paths = body?.match(/<path[^>]*>/g) ?? [];
  if (paths.length !== 1) throw new Error(`${icon}: expected a single path`);
  const d = paths[0].match(/ d="([^"]+)"/)?.[1];
  if (!d) throw new Error(`${icon}: no path data`);
  return `  // ${icon} by ${author}\n  ${id}: "${d}",`;
});
const authors = [...new Set(Object.values(PORTRAITS).map(([, a]) => a))];

const out = `// Generated by scripts/portraits.mjs (pnpm portraits). Do not edit.
// Icons from game-icons.net by ${authors.join(" and ")}, CC BY 3.0:
// https://creativecommons.org/licenses/by/3.0/

/** The icons' authors, for the credit line. */
export const PORTRAIT_AUTHORS = ${JSON.stringify(authors)};

/** Unit def id → SVG path data in a 512×512 view box. */
export const PORTRAITS: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(new URL("../src/battle/portraitIcons.ts", import.meta.url), out);
